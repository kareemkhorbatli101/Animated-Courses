/* bench2.js — regenerates dev/lab2-data.js.

   The hand-written bench (dev/lab-data.js) covers the kinds built in this
   pass with deliberately awkward data. This second bench covers every OTHER
   registered kind by lifting one real scene of it out of the book, so the
   shape under test is exactly the shape that ships. A kind the book does not
   yet use gets a hand-written scene in SUPPLEMENT below, because a registered
   renderer that nothing exercises is a renderer that rots.

   Run: node tools/bench2.js     (then: node tools/solve.js --lab) */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');

function load(p) {
  const src = fs.readFileSync(p, 'utf8'), w = {};
  new Function('window', src + '\n;return window.PAGE;')(w);
  return w.PAGE;
}

/* every kind a renderer registers */
const registered = new Set();
for (const f of fs.readdirSync(path.join(ROOT, 'assets')))
  if (/\.js$/.test(f))
    for (const m of fs.readFileSync(path.join(ROOT, 'assets', f), 'utf8')
                      .matchAll(/register\("([a-z0-9-]+)"/g)) registered.add(m[1]);

/* every kind the first bench already covers */
const benched = new Set();
for (const m of fs.readFileSync(path.join(ROOT, 'dev/lab-data.js'), 'utf8')
                  .matchAll(/kind: *"([a-z0-9-]+)"/g)) benched.add(m[1]);

/* first real scene of each remaining kind */
const want = [...registered].filter(k => !benched.has(k)).sort();
const found = {};
for (const u of fs.readdirSync(ROOT).filter(d => /^u\d\d$/.test(d)).sort()) {
  const dd = path.join(ROOT, u, 'data');
  if (!fs.existsSync(dd)) continue;
  for (const f of fs.readdirSync(dd).sort()) {
    let P; try { P = load(path.join(dd, f)); } catch (e) { continue; }
    if (!P || !P.scenes) continue;
    for (const s of P.scenes)
      if (want.includes(s.kind) && !found[s.kind])
        found[s.kind] = { where: `${u}/${f.replace(/\.js$/, '')}`, scene: s };
  }
}

/* kinds the book does not use yet: benched by hand so they cannot rot */
const SUPPLEMENT = {
  /* `read-only` is deliberately absent: the kind was removed from the
     registry once all 91 of its scenes became exercises. */
  order: {
    kind: 'order', n: 1,
    prompt: 'Put the words in order to make one sentence.',
    target: 'spacing the same hours over more days is what makes them stick',
    extra: ['because', 'which'],
    hint: 'Tap a word, or drag it here',
    why: 'The subject is a whole clause — <i>spacing the same hours over more days</i> — ' +
         'so the verb is singular <i>is</i>. The two spare words belong to no clause here.'
  }
};

const out = [];
want.forEach((k, i) => {
  const src = found[k] ? found[k].scene : SUPPLEMENT[k];
  if (!src) { console.error('  no scene and no supplement for kind: ' + k); process.exitCode = 1; return; }
  const s = JSON.parse(JSON.stringify(src));
  s.id = 'b' + i; s.section = i + 1; s.letter = 'A';
  s.sectionTitle = k + (found[k] ? ' — from ' + found[k].where : ' — hand-written, unused in the book');
  out.push('      /* ' + k + (found[k] ? ' — lifted from ' + found[k].where : ' — hand-written') + ' */\n' +
           JSON.stringify(s, null, 2).replace(/^/gm, '      '));
});

fs.writeFileSync(path.join(ROOT, 'dev/lab2-data.js'),
`/* lab2-data.js — GENERATED by tools/bench2.js. Do not hand-edit.
   One scene per registered kind that dev/lab-data.js does not cover, lifted
   from the book so the shape under test is the shape that ships. */
(function () {
  window.PAGE = {
    id: "lab2", unit: "u01", block: "l1", up: "../", tab: "ACADEMIC",
    objective: "Engine bench — every shipped kind the first bench does not cover",
    scenes: [
${out.join(',\n\n')}
    ]
  };
})();
`);
console.log(`dev/lab2-data.js: ${out.length} scenes, ${registered.size} kinds registered, ` +
            `${benched.size} on the first bench`);
