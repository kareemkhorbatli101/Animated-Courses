"""Render the plan document from the mapping, so the two cannot drift."""
from __future__ import print_function
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
los = json.load(open(os.path.join(HERE, 'los.json'), encoding='utf8'))
plan = json.load(open(os.path.join(HERE, 'plan.json'), encoding='utf8'))
TEXT = dict((s['code'], s['text']) for s in los['statements'])
SUB = los['subsections']

L = []
w = L.append
w('# CMA Part 2 — the four books')
w('')
w('Source: **%s**' % los['source'])
w('')
w('263 learning outcome statements, over four books of eighteen chapters.')
w('Every statement is placed; `check_plan.py` proves it, and fails the build')
w('if a later edit drops one.')
w('')
w('## The sequence, and why it is this one')
w('')
w('The LOS is written in exam order, which is not teaching order. The books')
w('follow the order the subject is actually built in:')
w('')
w('1. **Read the statements.** Everything else in Part 2 acts on numbers,')
w('   and Part 1 ended by preparing them. Book 1 opens on the very balance')
w('   sheet and income statement Part 1 closed with.')
w('2. **Pay for it.** What a company is worth, what money costs it, and')
w('   where it comes from — long-term first, then the working year.')
w('3. **Choose.** Decisions of rising size and horizon: one order, one')
w('   product line, one price, one machine, one company.')
w('4. **Guard it.** What can go wrong, what a currency does to you, and')
w('   what you owe whatever the numbers say.')
w('')
w('Two subsections move out of Section B, because the exam groups them by')
w('topic and a reader meets them by purpose:')
w('')
w('- **B.5 corporate restructuring** joins Book 3, at the end of the')
w('  capital-investment run. Valuing an acquisition by discounted cash')
w('  flow is the same act as valuing a machine, one order of magnitude up,')
w('  and B.5(f) says so in as many words.')
w('- **B.6 international finance** joins Book 4, beside enterprise risk.')
w('  B.6(d) and B.6(f) are hedging statements: "how currency futures,')
w('  swaps and options can be used to manage exchange rate risk", and')
w('  "recommend methods of managing exchange rate risk". That is risk')
w('  management, and it is taught with it.')
w('')
w('## The four books')
w('')
w('| | title | covers | chapters | statements | a chapter |')
w('|---|---|---|---|---|---|')
for b in plan['books']:
    n = sum(len(c[1]) for c in b['chapters'])
    w('| %d | **%s** — %s | %s | %d | %d | %.1f |'
      % (b['n'], b['title'], b['sub'], b['covers'],
         len(b['chapters']), n, n / float(len(b['chapters']))))
w('')
w('Part 1 ran 2.7 to 6.7 statements a chapter across its four books, so')
w('this spread sits inside what the series has already shipped.')
w('')
w('## The world')
w('')
w('%s' % plan['world'])
w('')
w('Book 1 analyses the statements Part 1 Book 1 prepared — the same')
w('comparative balance sheet at 31 December 2025 and 2024, the same income')
w('statement, the same statement of cash flows. They tie: assets of')
w('$31,672,600 against liabilities of $11,279,625 and equity of')
w('$20,392,975. A reader who worked Part 1 recognises every line, and a')
w('ratio that comes out at 3.32 can be traced back to a number he wrote')
w('himself. Barada Wholesale, Jordan Glass Co., Levant Commerce Bank and')
w('Gulf Factor Co. carry over with it.')
w('')
for b in plan['books']:
    w('---')
    w('')
    w('## Book %d — %s' % (b['n'], b['title']))
    w('')
    w('*%s.* %s.' % (b['sub'], b['covers']))
    w('')
    subs = sorted(set(c[:3] for _t, codes in b['chapters'] for c in codes))
    for k in subs:
        w('- **%s %s**' % (k, SUB.get(k, '')))
    w('')
    for ci, (title, codes) in enumerate(b['chapters'], 1):
        w('**%d. %s**' % (ci, title))
        w('')
        for c in codes:
            w('   - `%s` %s' % (c, TEXT[c]))
        w('')
out = os.path.join(os.path.dirname(HERE), '..', 'CMA_Part2_Plan.md')
open(os.path.abspath(out), 'w', encoding='utf8').write('\n'.join(L) + '\n')
print(os.path.abspath(out), len(L), 'lines')
