"""Unit 49 — Taxation and Public Finance.

Cycle 4 is the founding distinction of public finance: statutory
incidence, the person the law names, against economic incidence,
the person whose income falls. One rule divides the burden - it
settles on whichever side has the smaller capacity for adjustment,
because the other side moves until movement stops paying. Three
cases: land, where supply is fixed and the owner bears all of it;
a manufactured good with many producers and devoted customers,
where the charge goes into the price; and employer contributions,
where the literature puts a large share on wages, arriving as a pay
award slightly smaller than it would have been.

Cycle 5 attacks the assumption rather than the result. The
apportionment presupposes that the parties perceive the charge, and
the supermarket experiment - inclusive shelf labels against tax
added at the till, with the amount payable identical - shows demand
falling with visibility alone. Three consequences: a label is a
fiscal instrument; the survival of the employer contribution is
better explained by invisibility than by any argument for it, which
vindicates the statutory distinction cycle 4 dismissed; and a tax
nobody perceives distorts nothing, so it is efficient on the
standard criterion and objectionable on most others. Then the limit
on the objection: salience effects fade as the sum at stake rises.

Cycle 3 is the Danish audit experiment - forty thousand taxpayers,
random audit or none, returns set beside what the authority already
held. Understatement near zero on third-party reported income and
very large on self-reported income, from the same people on the same
form, so the explanation cannot be honesty.

Grammar: nominal clauses as subject and complement."""

