"""Unit 52 — Constitutional Design.

Cycle 4 is the functional argument for entrenchment, which is a
reversal: the orthodox description of a constitution as a limit
on government is accurate and by itself misleading, because the
argument begins from an incapacity rather than a danger. An
authority able to alter any undertaking at will cannot make one
anybody will act upon, since every assurance is discounted by the
probability of its own change of mind. Three measurable
consequences - the cost of borrowing, investment with long
horizons, and the peaceful transfer of office, which rests on a
defeated party expecting elections to continue - and then the four
devices, each raising the cost of amendment in a different
currency: supermajority, referendum, federal consent,
justiciability.

Cycle 5 separates two objections that are usually run together.
Time: an entrenched provision binds a generation with no part in
its adoption, so the commitment argument becomes one group binding
another. Agency: where a guarantee is justiciable, a contested
moral question is settled by officials nobody elected and no
electorate can reverse. Neither is answered by the benefits, since
both concede them and ask after their distribution. Then the
comparative record - eight of forty-four Australian referendums
carried since 1901, against texts amended annually and responsive
to nobody - and the conclusion that the formal threshold matters
less than real judicial independence and real alternation. The
defenders keep one card: an unenforced right is recoverable and an
unwritten one is not.

Cycle 3 is the South African certification of 1996. Thirty-four
principles agreed by the parties in 1993; an elected assembly to
write the text and an appointed court to certify compliance; a
unanimous refusal in September naming the entrenchment of the
amendment procedure and the protection of local government; no
rewriting and no comment on political choices; certification in
December. And the three conditions it depended on, because without
any one of them the episode is a constitutional crisis instead.

Grammar: long-range cohesion and anaphora - this and such with a
summary noun, the one-antecedent rule, the former and the latter,
substitution with one and do so."""

