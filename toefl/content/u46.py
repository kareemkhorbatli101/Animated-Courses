"""Unit 46 — Transport and Movement.

Cycle 4 states the proposition transport economics is built on -
travel is a behaviour with a price and the price is mostly time -
and then the corollary: added capacity in a congested city is
consumed by the traffic the addition itself brings out. The
measurement is the comparison of lane-kilometres built with
vehicle-kilometres driven across two decades of American
metropolitan areas, an elasticity near one, named the fundamental
law of road congestion; the insight itself is older, described in
1962 as a convergence of drivers from other routes, hours and
modes. Four mechanisms, the largest and slowest being relocation,
which no traffic model contains because it is a change in where
people live rather than in how they travel.

Cycle 5 attacks the inference rather than the finding. A lane
consumed by new journeys has not reduced delay and has increased
the number of people reaching a destination, and the extra
journeys are not waste, since somebody valued each enough to make
it. The fault is the price: a driver pays the delay he suffers and
nothing for the delay he imposes. Hence a charge rather than a
prohibition - Singapore, London, Stockholm, where the referendum
followed the trial and support rose - against Edinburgh,
Manchester and twenty years of litigation in New York. Then the
cost of its own position: a flat charge is regressive, the answer
is reinvestment of the revenue, and whether that is politically
available is left open.

Cycle 3 is traffic evaporation: Seoul in 2003, San Francisco after
the 1989 earthquake, and the review of some sixty capacity
reductions - with the conditions the effect depends on stated, so
that the case cannot be quoted at a rural road.

Grammar: correlative and parallel structures."""

