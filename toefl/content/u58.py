"""Unit 58 - Monopoly and Regulation.

Cycle 3 is the dissolution of Standard Oil in 1911 into
thirty-four companies, the severest remedy in American
competition law and one imposed perhaps a dozen times since. The
conduct was not the refining but the railway arrangement -
rebates on its own freight and a payment on every barrel its
competitors shipped, so that a rival’s growth financed the
firm it was fighting. Two complications are conceded: the share
had already fallen from above ninety per cent to about
sixty-four, and the successors went to the same shareholders in
proportion, the pieces being worth more than the whole within a
decade. What the case founded is the distinction between the
position and the conduct.

Cycle 4 derives the instruments from the cost condition. Where
most of the expenditure precedes the first unit, average cost
falls with volume and one supplier is cheaper than two, so the
position is a consequence of the technology and the surplus above
the return needed to attract capital is the rent. Contestability
would discipline the holder if entry were free, and fails because
the expenditure is sunk. Rate-of-return regulation pays for
ownership, with the Averch-Johnson consequence of an asset base
beyond need; a price cap pays for economy and invites a
deterioration of service.

Cycle 5 accepts the instruments and doubts the institution.
Capture is described as a mechanism of staffing, evidence and
attention rather than dishonesty: the only competent staff come
from the industry, the firm’s submission is the only
submission, and disbelieving it costs the authority its own
budget. The recommended remedy is narrow - regulate the one asset
nobody can build twice and publish one access price - and the
two recorded failures are conceded: nobody agrees what counts as
the network, and a separated owner has no commercial interest in
what runs over it."""

