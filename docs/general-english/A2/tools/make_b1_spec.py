def main():
    src = open(os.path.join(A2, 'spec', 'golden.yaml'), encoding='utf-8').read()
    out = src
    # the budget block, matched by its own extent
    m = re.search(r'^word_budget:\n(?:.*\n)*?^model_allowance_words: .*$',
                  out, re.M)
    assert m, 'word_budget block not found'
    out = out[:m.start()] + BUDGET + out[m.end():]
    for what, old, new in SUBS:
        if old is None:
            continue
        assert old in out, f'anchor missing for: {what}\n{old[:90]!r}'
        out = out.replace(old, new, 1)
    # 41 figures from Unit 1, so the sparse/dense split goes
    out = out.replace(
        '  per_unit: 14\n  source_per_unit: 4\n',
        '  per_unit: 41\n  source_per_unit: null\n'
        # The depiction law, G34 and G35. Set at B1 and not at A2, because A2's
        # 820 figures were drawn before it existed: measured when the law was
        # written, 332 of A2's 1,354 depictive icon/label pairs (25%) would fail
        # G34 and would have to be re-chosen by hand. 00-MASTER-PLAN.md 4c
        # carries that decision and what reversing it would cost. The allow list
        # is for pairs a human has judged depictive that the map cannot see; it
        # is empty, and every entry added to it needs a reason beside it.
        '  depictive_icons: true\n'
        '  icon_allow: []\n')
    # The clarity law, family N. Set at B1 and not at A2 for the same reason as
    # the depiction law: A2's twenty units were written before a reader said the
    # passages made them feel stupid, and the register fault that review named is
    # in A2's prose too. 00-MASTER-PLAN.md 4d carries the decision.
    out = out.replace(
        '\nlanguage:\n',
        '\nlanguage:\n'
        '  # --- the clarity law (family N) ---------------------------------\n'
        '  clarity_law: true\n'
        '  # share of an open answer\'s content words that must appear in the\n'
        '  # passage it is asked about (N03)\n'
        '  clarity_answer_share: 0.5\n'
        '  # a dialogue turn longer than this is a speech, not a turn (N06)\n'
        '  clarity_turn_words_max: 55\n', 1)
    m = re.search(r'^  slots:\n(?:    .*\n|    #.*\n)*?(?=^  # -{10,} the 41 slots)',
                  out, re.M)
    assert m, 'sparse slots block not found'
    dm = re.search(r'^  dense_slots:\n((?:    .*\n)*)', out, re.M)
    assert dm, 'dense_slots block not found'
    out = out[:m.start()] + '  slots:\n' + dm.group(1) + out[m.end():]
    # drop the whole dense mechanism and the comment that introduced it
    out = re.sub(r'^  # -{10,} the 41 slots\n(?:  #.*\n)*  dense_units:\n'
                 r'(?:    .*\n)*  dense_per_unit: \d+\n  dense_slots:\n'
                 r'(?:    .*\n)*', '', out, flags=re.M)
    hdr = ('# The frozen architecture for B1. GENERATED from ../A2/spec/golden.yaml\n'
           '# by tools/make_b1_spec.py -- do not hand-edit: re-run the generator so\n'
           '# the structural parity with A2 stays a diff rather than a promise.\n')
    out = hdr + out.split('\n', 2)[2]
    p = os.path.join(ROOT, 'spec', 'golden.yaml')
    open(p, 'w', encoding='utf-8').write(out)
    open(os.path.join(ROOT, 'spec', 'golden.sha256'), 'w').write(
        hashlib.sha256(out.encode()).hexdigest() + '\n')
    for f in ('palette.yaml',):
        import shutil
        shutil.copy(os.path.join(A2, 'spec', f), os.path.join(ROOT, 'spec', f))
    print(f'wrote spec/golden.yaml ({len(out.splitlines())} lines), '
          f'hash-locked, palette copied')
    return 0


if __name__ == '__main__':
    sys.exit(main())
