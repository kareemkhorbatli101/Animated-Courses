"""Writes build/check-report.md: the 600 passes plus what the passages actually measure."""
import collections
import glob
import os
import statistics as st
import subprocess
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lex                                                     # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = yaml.safe_load(open(os.path.join(ROOT, 'data', 'spec.yaml')))


def measure():
    data = {}
    for lv in (1, 2, 3, 4):
        d = collections.defaultdict(list)
        for f in sorted(glob.glob(os.path.join(ROOT, 'data', 'passages', '*-L%d.yaml' % lv))):
            for x in yaml.safe_load(open(f))['passages']:
                flat = ' '.join(x['passage'].split())
                w, sents = lex.words(flat), lex.sentences(flat)
                sl = [len(lex.words(s)) for s in sents]
                d['W'].append(len(w))
                d['S'].append(len(sents))
                d['M'].append(sum(sl) / len(sl))
                d['X'].append(max(sl))
                d['F'].append(lex.flesch_kincaid(flat))
                d['T'].append(len(x.get('terms') or []))
                ranks = [lex.rank(t) for t in w]
                d['R'].append(st.median([r for r in ranks if r]))
        data[lv] = d
    return data


def above_band():
    out = []
    for lv in (1, 2, 3, 4):
        band = SPEC['levels'][lv]['known_band']
        for f in sorted(glob.glob(os.path.join(ROOT, 'data', 'passages', '*-L%d.yaml' % lv))):
            for x in yaml.safe_load(open(f))['passages']:
                flat = ' '.join(x['passage'].split())
                props = lex.proper_nouns(flat)
                terms = {p for t in (x.get('terms') or []) for p in t['term'].lower().split()}
                over = set()
                for w in lex.words(flat):
                    lw = w.lower()
                    if w in props or lw in props or lw in terms:
                        continue
                    r = lex.rank(lw)
                    if r and r > band:
                        over.add(lw)
                out.append((len(over), x['id'], sorted(over)))
    out.sort(reverse=True)
    return out


def main():
    data, over = measure(), above_band()
    res = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'checks.py')],
                         capture_output=True, text=True).stdout.strip()
    L = SPEC['levels']
    o = ['# Check report — *Reading the Five Fields*', '',
         'Generated by `tools/report.py`, which runs `tools/checks.py` and then measures the',
         'passages. Every number below is measured from `data/passages/*.yaml`, not asserted.', '',
         '## 1. The 600 passes', '', '```', res, '```', '',
         '## 2. The language ladder as achieved', '',
         '| | L1 | L2 | L3 | L4 |', '|---|---|---|---|---|']

    def band(label, a, b):
        o.append('| %s | %s |' % (label, ' | '.join('%s–%s' % (L[lv][a], L[lv][b]) for lv in (1, 2, 3, 4))))

    def cap(label, key):
        o.append('| %s | %s |' % (label, ' | '.join(str(L[lv][key]) for lv in (1, 2, 3, 4))))

    def row(label, key, fmt='%.1f', agg=st.mean):
        o.append('| %s | %s |' % (label, ' | '.join(fmt % agg(data[lv][key]) for lv in (1, 2, 3, 4))))

    band('Words, band enforced', 'words_min', 'words_max')
    row('Words, mean', 'W')
    row('Words, min', 'W', '%.0f', min)
    row('Words, max', 'W', '%.0f', max)
    band('Mean sentence, band', 'sent_mean_min', 'sent_mean_max')
    row('Mean sentence, mean', 'M')
    row('Mean sentence, min', 'M', '%.1f', min)
    row('Mean sentence, max', 'M', '%.1f', max)
    cap('Longest sentence, cap', 'sent_max')
    row('Longest sentence, max observed', 'X', '%.0f', max)
    band('Flesch–Kincaid, band', 'fk_min', 'fk_max')
    row('Flesch–Kincaid, mean', 'F')
    row('Flesch–Kincaid, min', 'F', '%.1f', min)
    row('Flesch–Kincaid, max', 'F', '%.1f', max)
    cap('Sentences, floor', 'sents_min')
    row('Sentences, min observed', 'S', '%.0f', min)
    o.append('| Assumed-known band | %s |'
             % ' | '.join(format(L[lv]['known_band'], ',d') for lv in (1, 2, 3, 4)))
    row('Median word rank', 'R')
    row('Field terms per passage, mean', 'T', '%.2f')
    o += ['',
          'The three monotonic ladders — readability, sentence length and median word rank —',
          'rise at every step. Levels 3 and 4 are closer in readability (11.9 against 13.1) than',
          'in what they ask of the reader, which is the honest description of the difference',
          'between *evidence* and *dispute*.', '',
          '## 3. The 98 per cent coverage rule', '',
          "At most six running words per passage may fall outside the level's assumed-known",
          'band, counting neither proper nouns nor declared field terms. Distribution of the',
          'count of distinct above-band words, over all 200 passages:', '',
          '| above-band words | 0 | 1 | 2 | 3 | 4 | 5 | 6 |',
          '|---|---|---|---|---|---|---|---|']
    dist = collections.Counter(n for n, _, _ in over)
    o.append('| passages | %s |' % ' | '.join(str(dist.get(i, 0)) for i in range(7)))
    o += ['', 'The passages that sit at the ceiling, with the words counted:', '']
    for n, i, ws in over[:8]:
        o.append('- **%s** (%d): %s' % (i, n, ', '.join(ws)))
    o += ['',
          'A capitalized name that opens a sentence is counted here rather than exempted, so',
          'the budget is spent conservatively: *antoine* in PHY-S07-L1 is Antoine Lavoisier.', '',
          '## 4. What these checks do not establish', '',
          'They are structural. They cannot tell whether a passage is true, and they cannot',
          'tell whether it is worth reading. Each passage carries a `facts` list of at least',
          'three checkable claims so that a reviewer can verify the content quickly; the',
          'figures are the standard published ones where a figure is given at all. The five',
          'fields and the fifty strands are a curricular judgment, not an official syllabus:',
          'the College Board publishes no subject list and no reading list.', '']
    out = os.path.join(ROOT, 'build', 'check-report.md')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w').write('\n'.join(o))
    print('wrote', out)


if __name__ == '__main__':
    main()
