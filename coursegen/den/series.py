"""English for Dentists — International Edition — series parameters.

The course is for dentists who practise in English without having grown up in
it: associates and principals in general practice, hospital and community
dentists, dentists with a special interest who receive referrals and write
reports, clinical governance leads who handle the weeks when something has gone
wrong, and clinical directors who must answer to partners, regulators and the
public in a second language.

The edition's spine is the fact that makes dental English what it is: the
patient is awake, is paying, and cannot answer once you have started. Every
sentence that matters — what is wrong, what you propose, what it will cost,
what could go wrong, what happens if nothing is done, and how to make you stop
— has to be said before the first instrument touches the tooth. After that the
patient can lift a hand and nothing else. A consent that the patient could not
repeat back afterwards was not a consent; an estimate that moved without a
sentence was not an estimate; a record written after the complaint arrived is a
different document from a record written on the day.

The books teach professional communication and professional writing. They do
not teach dentistry and they give no clinical guidance: no diagnosis, no
technique, no named material, no instrument setting, no drug, no dose and no
radiographic interpretation appears anywhere in the series. Every clinical
decision in these pages belongs to a clinician who is named as owning it, and
every clinical judgement belongs to the dentist at the chair rather than to a
rule printed in a coursebook. Nor do the books give legal, regulatory or
financial advice: every unit that touches consent, records, fees, insurance,
raising concerns, inspection, complaints or fitness to practise says in its own
text that local law and the practice's own written procedures govern it, and
that the dentist's job is to use the route rather than to invent one. All sums
of money are illustrative and belong to invented practices.

No vendor, product, model, platform, living official or political claim appears
anywhere. Practices, hospitals, laboratories, insurers and committees are
invented; cities are real. All figures are illustrative and belong to invented
organisations.

The series signature is the moment a dentist has to say the hard thing while
the patient can still answer: Part 10 of every unit, The Sentence You Must Say
Before You Start.
"""

