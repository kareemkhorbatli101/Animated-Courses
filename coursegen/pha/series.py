"""English for Pharmacists — International Edition — series parameters.

The course is for pharmacists who practise in English without having grown up in
it: community pharmacists and pharmacy managers, dispensary and clinical
pharmacists, ward and medicines information pharmacists, procurement and supply
pharmacists, governance and superintendent pharmacists, and chief pharmacists
who must answer to committees, regulators and the public in a second language.

The edition's spine is the fact that makes pharmacy English what it is: in
pharmacy a sentence is a safety device. One word, one number, one unit and one
missing line decide what somebody takes, and the sentence has to survive being
read by a person who was not there when it was written. An instruction a patient
cannot repeat back, a query that was never asked, a strength written without its
units, a label that says what the prescriber meant rather than what the
prescription says, a near miss that nobody wrote down: each is a failure of
language with a consequence that a patient eventually carries.

The books teach professional communication and professional writing. They do not
teach therapeutics and they give no clinical guidance: no dose, no strength, no
regimen, no interaction, no indication and no named medicine appears anywhere in
the series. Every therapeutic decision in these pages belongs to a prescriber who
is named as owning it, and every clinical check belongs to the pharmacist's own
judgement at the bench rather than to a rule printed in a coursebook. Nor do the
books give legal or regulatory advice: every unit that touches supply law,
registers, unlicensed items, recalls, refusal, raising concerns, inspection or
fitness to practise says in its own text that local law and the employer's own
standard operating procedures govern it, and that the pharmacist's job is to use
the route rather than to invent one.

No vendor, product, model, platform, living official or political claim appears
anywhere. Hospitals, pharmacies, wholesalers and committees are invented; cities
are real. All figures are illustrative and belong to invented organisations.

The series signature is the moment a pharmacist has to put a question, a refusal
or a correction in front of somebody who does not want it, and stay there: Part
10 of every unit, The Question You Have to Ask.
"""

