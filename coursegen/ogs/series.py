"""English for the Oil and Gas Industries — Syrian Edition — series parameters.

The course is for the people who run, maintain and account for oil and gas
operations in Syria and who have to do it in English: process operators and
panel operators, shift supervisors, HSE officers, production and commissioning
engineers, maintenance and turnaround planners, contracts and procurement
staff, operations superintendents, and the managers who answer to a ministry,
a joint-venture partner, a board and the people who live beside the plant.

It is a Syrian edition because the work it describes is restart work. Fields
and plants are coming back after years of damage and deferred maintenance;
international operators, service companies and EPC contractors are returning;
and a Syrian operator and a contractor's engineer now stand at the same valve
holding two different procedures, in a second language, under schedule
pressure. The language of that restart is the language this course teaches.

The edition's spine is the fact that makes oil and gas English what it is: on a
plant the words are part of the equipment. A permit is not paperwork about the
work; it is the authority for the work. A handover is not a courtesy; it is the
transfer of custody of a hazard. A reading without its unit is not a small
error; it is a wrong number in a safe place.

And because the whole system rests on one authority that anybody may use and
nobody may be punished for using, the series signature is Stop the Job: the
sentence that halts work, said upwards, said to a client, said under schedule
pressure, by somebody who may turn out to have been wrong.
"""

