"""English for Nurses — International Edition — series parameters.

The course is for nurses who work in English without having grown up in it:
staff nurses on international wards, nurses recruited across borders, nurses
caring for patients who share no language with them, and anyone preparing for
registration, placement or practice abroad who must receive a handover, watch a
patient, write a note, call for help and teach a family in a second language.

The edition's spine is the fact that makes nursing English what it is: the
nurse is the person who is there. She sees the change first, and nothing she
sees helps the patient until it has become a sentence somebody else acts on. A
deterioration noticed and not escalated, a handover that left out the one thing
that mattered, an instruction a patient could not follow, a refusal nobody
recorded — each is a failure of language with a clinical consequence.

The books teach clinical communication and clinical writing. They do not teach
nursing practice, give clinical guidance or recommend any treatment: no dose, no
regimen and no diagnostic rule appears anywhere. Clinical detail is
deliberately generic and exists only to carry the language. Every unit that
touches a clinical decision says in its own text that the decision belongs to
the treating clinician, and every unit that touches a professional duty says
that local law and local policy govern it.

No vendor, product, model, platform, living official or political claim appears
anywhere. Hospitals, clinics and homes are invented; cities are real.

The series signature is the moment a nurse must stop writing and say something
out loud to somebody who does not want to hear it: Part 10 of every unit,
Speaking Up.
"""

