"""English for Hospital Management — International Edition — series parameters.

The course is for the people who run hospitals in English without having grown
up in it: operations and site managers, ward and department managers, workforce
and finance leads, performance and information managers, procurement and estates
managers, and directors preparing for boards, regulators and the public in a
second language.

The edition's spine is the fact that makes management English what it is: a
hospital runs on sentences that say who will do what, by when, and — far harder
— what will not be done at all. A bed state nobody could act on, a request with
no number in it, a decision taken in a corridor and recorded nowhere, a target
that bought one figure by wrecking another, a paper that asked for a discussion
rather than a decision: each is a failure of language with an operational cost
that somebody eventually pays in a bed, a shift or a list.

The books teach management communication and management writing. They do not
teach clinical practice, give clinical guidance or recommend any treatment: no
dose, no regimen and no diagnostic rule appears anywhere, and every clinical
decision in these pages belongs to a clinician who is named as owning it. Nor do
the books give legal, financial, employment or regulatory advice: every unit that
touches employment process, procurement, disclosure, consultation or a
regulator's powers says in its own text that local law and the organisation's
own policy govern it, and that the manager's job is to use the route rather than
to invent one.

No vendor, product, model, platform, living official or political claim appears
anywhere. Hospitals, clinics, suppliers and committees are invented; cities are
real. All figures are illustrative and belong to invented organisations.

The series signature is the moment a manager has to put a figure or a fact in
front of somebody who does not want it, and stay in the room: Part 10 of every
unit, The Unwelcome Number.
"""

